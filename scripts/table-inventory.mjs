// Read-only: lists every file that renders a data table and which shared pieces it uses. Run: node scripts/table-inventory.mjs
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../frontend/src/', import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.tsx$/.test(name)) files.push(path);
  }
})(root);

const rows = [];
for (const file of files) {
  const source = readFileSync(file, 'utf8');
  const tables = (source.match(/<table[\s>]/g) || []).length;
  if (!tables) continue;
  rows.push({
    file: relative(root, file), tables,
    container: /TableWrap/.test(source) ? 'TableWrap' : /TableScroll/.test(source) ? 'TableScroll' : 'none',
    cards: /mobileLayout="cards"/.test(source) ? 'cards' : 'scroll',
    pagination: /<Pagination|FinancialPagination/.test(source) ? 'yes' : 'no',
    period: /PeriodFilter/.test(source) ? 'yes' : 'no',
    export: /ExportButton|exportTable|export/i.test(source) ? 'yes' : 'no',
    bulk: /BulkActionBar|useBulkSelection/.test(source) ? 'yes' : 'no',
    search: /type="search"|placeholder="Search|placeholder=\{?["'`]Search/i.test(source) ? 'yes' : 'no',
  });
}
rows.sort((a, b) => a.file.localeCompare(b.file));
const module = (f) => (f.match(/(?:app\/\([a-z]+\)\/|components\/)([a-z-]+)/i) || [])[1] || 'other';
console.log('# Table inventory (generated by scripts/table-inventory.mjs)\n');
console.log(`Files with tables: ${rows.length}; table elements: ${rows.reduce((n, r) => n + r.tables, 0)}; using the shared container: ${rows.filter((r) => r.container !== 'none').length}\n`);
console.log('| Module | File | Tables | Container | Phone layout | Pagination | Date filter | Export | Bulk | Search |\n|---|---|---|---|---|---|---|---|---|---|');
for (const r of rows) console.log(`| ${module(r.file)} | ${r.file} | ${r.tables} | ${r.container} | ${r.cards} | ${r.pagination} | ${r.period} | ${r.export} | ${r.bulk} | ${r.search} |`);
