// Read-only: lists every file that renders a <form> and how much of the shared form kit it uses. Run: node scripts/form-inventory.mjs
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const apps = ['frontend', 'super-admin', 'website'];
const root = new URL('../', import.meta.url).pathname;
const rows = [];
for (const app of apps) {
  const base = join(root, app, 'src');
  const files = [];
  (function walk(dir) {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.tsx$/.test(name)) files.push(path);
    }
  })(base);
  for (const file of files) {
    const s = readFileSync(file, 'utf8');
    const forms = (s.match(/<form[\s>]/g) || []).length;
    if (!forms) continue;
    rows.push({
      app, file: relative(join(root, app, 'src'), file), forms,
      container: /<Drawer[^>]*side="center"/.test(s) ? 'dialog' : /<Drawer/.test(s) ? 'drawer' : /<Modal|role="dialog"/.test(s) ? 'modal' : /page\.tsx$/.test(file) ? 'page' : 'inline',
      kit: /components\/ui\/Form"|from "\.\/Form"|from "@\/components\/ui\/Form"/.test(s) ? 'Field/Input' : 'none',
      rawInputs: (s.match(/<input[\s>]/g) || []).length + (s.match(/<select[\s>]/g) || []).length + (s.match(/<textarea[\s>]/g) || []).length,
      footer: /FormFooter/.test(s) ? 'FormFooter' : 'custom',
      upload: /type="file"/.test(s) ? 'file' : '',
    });
  }
}
rows.sort((a, b) => a.app.localeCompare(b.app) || a.file.localeCompare(b.file));
const total = rows.reduce((n, r) => n + r.forms, 0);
console.log('# Form inventory (generated by scripts/form-inventory.mjs)\n');
console.log(`Files with forms: ${rows.length}; <form> elements: ${total}; using the shared Field/Input kit: ${rows.filter((r) => r.kit !== 'none').length}; using FormFooter: ${rows.filter((r) => r.footer === 'FormFooter').length}\n`);
console.log('| App | File | Forms | Container | Shared Field kit | Raw inputs left | Footer | Upload |\n|---|---|---|---|---|---|---|---|');
for (const r of rows) console.log(`| ${r.app} | ${r.file} | ${r.forms} | ${r.container} | ${r.kit} | ${r.rawInputs} | ${r.footer} | ${r.upload} |`);
