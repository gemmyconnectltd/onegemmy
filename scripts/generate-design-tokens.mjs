import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('design-system/tokens.json', root), 'utf8'));
const declarations = Object.entries(tokens.light).map(([key, value]) => `  --${key}: ${value};`).join('\n');
const dark = Object.entries(tokens.dark).map(([key, value]) => `  --${key}: ${value};`).join('\n');
const output = `/* Generated by scripts/generate-design-tokens.mjs. Edit tokens.json. */
:root {
  color-scheme: light;
${declarations}
  --primary: ${tokens.primary};
  --accent: var(--primary);
  --primary-hover: ${tokens.primaryHover};
  --primary-active: ${tokens.primaryActive};
  --primary-light: ${tokens.primaryLight};
  --primary-border: ${tokens.primaryBorder};
  --primary-foreground: #FFFFFF;
  --secondary: var(--card);
  --secondary-foreground: var(--foreground);
  --card-foreground: var(--foreground);
  --popover: var(--card);
  --popover-foreground: var(--foreground);
  --muted-foreground: var(--muted);
  --accent-foreground: #FFFFFF;
  --input: var(--border);
  --ring: var(--primary);
  --destructive: ${tokens.error};
  --success: ${tokens.success};
  --warning: ${tokens.warning};
  --error: ${tokens.error};
  --radius: 8px;
  --sidebar: var(--card);
  --sidebar-hover: var(--primary-light);
  --sidebar-primary: var(--primary);
  --sidebar-ring: var(--primary);
  --sidebar-accent: var(--primary);
  --sidebar-accent-foreground: var(--primary-foreground);
  --sidebar-foreground: var(--foreground);
  --sidebar-border: var(--border);
  --type-title: ${tokens.typography.title}px;
  --type-section: ${tokens.typography.section}px;
  --type-card: ${tokens.typography.card}px;
  --type-body: ${tokens.typography.body}px;
  --type-label: ${tokens.typography.label}px;
  --type-helper: ${tokens.typography.helper}px;
}
.dark {
  color-scheme: dark;
${dark}
  --primary-light: color-mix(in srgb, var(--primary) 12%, var(--card));
  --primary-border: color-mix(in srgb, var(--primary) 35%, var(--card));
  --success: #4ADE80;
  --warning: #FBBF24;
  --error: #F87171;
}
`;
const path = new URL('design-system/tokens.css', root);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw Error('Generated tokens are stale. Run node scripts/generate-design-tokens.mjs');
} else { writeFileSync(path, output); console.log(`Generated ${fileURLToPath(path)}`); }
