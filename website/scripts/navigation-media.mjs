import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, watch } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const websiteRoot = fileURLToPath(new URL('../', import.meta.url));
export function buildMediaManifest(publicRoot) {
  const manifest = {};
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && /\.(avif|webp|png|jpe?g|svg)$/i.test(entry.name)) {
        const asset = `/${relative(publicRoot, path).replaceAll('\\', '/')}`;
        const version = createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 12);
        manifest[asset] = `${asset}?v=${version}`;
      }
    }
  }
  for (const directory of ['marketing', 'screenshots']) visit(join(publicRoot, directory));
  return manifest;
}
export function syncMediaManifest(root = websiteRoot, { check = false } = {}) {
  const manifest = buildMediaManifest(join(root, 'public'));
  const output = '// Generated by scripts/navigation-media.mjs. Update source images/configuration, not this file.\nexport const navigationMedia: Readonly<Record<string, string>> = '+JSON.stringify(manifest, null, 2)+';\n';
  const target = join(root, 'src/lib/navigation-media.generated.ts');
  let previous = '';
  try { previous = readFileSync(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (output !== previous) {
    if (check) throw new Error("Navigation media manifest is stale. Run npm run media:sync.");
    writeFileSync(target, output);
  }
  return manifest;
}
export function watchMediaManifest(root = websiteRoot) {
  let timer;
  const update = () => { clearTimeout(timer); timer = setTimeout(() => syncMediaManifest(root), 150); };
  const watchers = ['marketing', 'screenshots'].map(directory => watch(join(root, 'public', directory), { recursive: true }, update));
  return () => { clearTimeout(timer); watchers.forEach(watcher => watcher.close()); };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) syncMediaManifest(websiteRoot, { check: process.argv.includes("--check") });
